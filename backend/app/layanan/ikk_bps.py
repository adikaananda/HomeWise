def _cocok_alamat(alamat: str):
    if not alamat:
        return None
    teks = alamat.lower()
    for kata, provinsi in ALIAS_WILAYAH:
        if kata in KATA_PENDEK:
            if re.search(rf"\b{re.escape(kata)}\b", teks):
                return provinsi
        elif kata in teks:
            return provinsi
    return None


def _cocok_koordinat(lat, lng):
    if lat is None or lng is None:
        return None
    try:
        lat_f, lng_f = float(lat), float(lng)
    except (TypeError, ValueError):
        return None
    for lat_min, lat_maks, lng_min, lng_maks, provinsi in KOTAK_KOORDINAT:
        if lat_min <= lat_f <= lat_maks and lng_min <= lng_f <= lng_maks:
            return provinsi
    return None


def tentukan_indeks_wilayah(alamat=None, lat=None, lng=None, bawaan=1.0) -> dict:
    """Menentukan indeks kemahalan konstruksi BPS 2024 dari alamat atau koordinat properti."""
    provinsi = _cocok_alamat(alamat) or _cocok_koordinat(lat, lng)
    if provinsi and provinsi in IKK_PROVINSI_2024:
        ikk = IKK_PROVINSI_2024[provinsi]
        return {
            "indeks": round(ikk / 100.0, 3),
            "ikk": ikk,
            "provinsi": provinsi,
            "sumber": "IKK BPS 2024",
        }
    nilai_bawaan = float(bawaan or 1.0)
    return {
        "indeks": nilai_bawaan,
        "ikk": round(nilai_bawaan * 100.0, 2),
        "provinsi": None,
        "sumber": "Konfigurasi bawaan",
    }
